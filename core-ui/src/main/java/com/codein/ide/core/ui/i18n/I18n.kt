package com.codein.ide.core.ui.i18n

import android.content.Context
import java.util.Locale

/**
 * Codein's interface language. The UI is written in English; [tr] returns the Indonesian text for
 * a known English string when the chosen language is Indonesian (or "system" on an Indonesian
 * device), and the English text otherwise. Code, file names, log output and AI replies are never
 * translated here (the AI already answers in the device language).
 */
object I18n {
    enum class Language(val code: String, val displayName: String) {
        System("system", "System default"),
        English("en", "English"),
        Indonesian("id", "Bahasa Indonesia"),
    }

    private const val PREFS = "codein_ui"
    private const val KEY = "language"

    @Volatile
    var language: Language = Language.System
        private set

    /** True when strings are shown in Indonesian. */
    val indonesian: Boolean
        get() = when (language) {
            Language.Indonesian -> true
            Language.English -> false
            Language.System -> Locale.getDefault().language in setOf("in", "id")
        }

    /** Reads the saved choice; call once from Application.onCreate before any UI is shown. */
    fun load(context: Context) {
        val code = context.getSharedPreferences(PREFS, Context.MODE_PRIVATE).getString(KEY, Language.System.code)
        language = Language.entries.firstOrNull { it.code == code } ?: Language.System
    }

    /** Saves the choice; the caller recreates the activity so every screen picks it up. */
    fun set(context: Context, value: Language) {
        context.getSharedPreferences(PREFS, Context.MODE_PRIVATE).edit().putString(KEY, value.code).apply()
        language = value
    }

    fun translate(text: String): String = if (indonesian) Indonesian[text] ?: text else text

